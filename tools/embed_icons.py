#!/usr/bin/env python3
"""Embed site/favicon.svg|ico + apple-touch-icon.png into worker/worker.js between the ICONS markers (no deploy-script change needed)."""
import os, base64, re
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
b = lambda f: base64.b64encode(open(os.path.join(root, 'site', f), 'rb').read()).decode()
svg = open(os.path.join(root, 'site/favicon.svg')).read().replace('\\', '\\\\').replace('`', '\\`')
block = ("/* ICONS:BEGIN (generated by tools/embed_icons.py from site/favicon.*; brand mark = boot-animation Z) */\n"
         f"const FAVICON_SVG = `{svg}`;\nconst FAVICON_ICO = '{b('favicon.ico')}';\nconst APPLE_ICON = '{b('apple-touch-icon.png')}';\n/* ICONS:END */")
p = os.path.join(root, 'worker/worker.js'); s = open(p).read()
if '/* ICONS:BEGIN' in s: s = re.sub(r'/\* ICONS:BEGIN.*?/\* ICONS:END \*/', lambda m: block, s, flags=re.S)
else: s = s.replace("const store = env =>", block + "\nconst b64bin = s => Uint8Array.from(atob(s), c => c.charCodeAt(0));\nconst store = env =>", 1)
open(p, 'w').write(s); print('embedded')
